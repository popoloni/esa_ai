#!/usr/bin/env python3
"""Prepare untouched Spec Kit scaffolding for a separately observed model episode.

No model is called and no specification is generated by this preparation script.
The original authored before/after answers are deliberately not copied.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import shutil

HERE = Path(__file__).resolve().parent

TASK = """# Generate a candidate explanation-only Treasury specification

Read the supplied inputs/specification.json, discovery_handoff.json,
case_oracle.json, assessment.json, policy sources and source/treasury/routing.py.
Use the retained Spec Kit 1.2.2 specification, plan and tasks templates and
relevant skill instructions. Apply them through the actual dispatch interface;
do not claim that native Codex slash commands ran unless that was observed.

Produce a coherent candidate spec.md, plan.md and tasks.md in the current
orchestrator attempt's artifacts/ directory. Preserve all five requirement IDs,
all eight scenario IDs and their values, the source and decision owners,
BR-001/v1 and the exact EUR 5000 boundary. Explain why the proposed solution
shows a recommendation without authorizing payment. Treat benefit as an
unvalidated hypothesis. Keep human requirements approval pending and dependent
implementation/release work blocked. Do not manufacture a passed human review.

Use only this input bundle and the current request. Do not inspect neighboring
book chapters, reference answers, authored before/after specimens, prior review
findings or other workspaces. This is an instruction boundary in a shared
filesystem, not a technical access barrier; report any actual prior exposure.
Do not change any input, request, plan, controller, policy or source file. Do not
install clients, call external services, use credentials, implement code, or
deploy. Write only within the current attempt. No planted flaw is requested.

Where an unanswered question prevents a decision, state the question and keep
that decision pending. Retain a complete final response in RAW_RESPONSE.md,
including sources read, assumptions, changes, unresolved questions and what
was actually checked. Submit the request-bound artifact hashes using the
external_worker.py submission contract. Report the actual interface and any
exposed model identity; leave unavailable version, usage or cost fields null.

The coordinator must retain the first output before requesting a correction.
An independent fresh-context reviewer will inspect it. A model review cannot
approve business requirements, payment, or production release.
"""

REVIEW = """Independently review the generated specification, plan and tasks against
the supplied fixed requirements, case oracle, discovery evidence and policy
sources. Read the generation result through the dependency response path and
verify each referenced artifact hash before using it. Inspect exact equality,
invalid amounts, policy provenance, all five requirements and eight cases,
payment authority, unknown benefit, dependencies and the pending human decision.
Do not copy the author's review or inspect external reference answers. State
each concrete defect, file location, evidence and proposed correction; a clean
review is permitted when justified. Write review.json and RAW_RESPONSE.md in
this attempt, preserve first outputs, and submit their hashes. A review is an
agent assessment, not human acceptance. Do not modify the generation output.
"""


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inventory(root):
    files = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"Symlink is not supported in a generation bundle: {path}")
        if path.is_file():
            files[str(path.relative_to(root))] = {"sha256": sha(path), "bytes": path.stat().st_size}
    return files


def prepare(output):
    output = output.absolute()
    for part in [output, *output.parents]:
        if part.is_symlink():
            raise ValueError("Output path has a symlink component")
    companion = HERE.parents[1]
    if any(output.is_relative_to(companion / name) for name in ("repo", "reader_side")):
        raise ValueError("Use a new directory outside the protected exercise trees")
    source = HERE / "evidence/revision_d4_fresh_scaffold"
    original = inventory(source)
    output.mkdir(parents=True, exist_ok=False)
    target = output / "inputs"
    shutil.copytree(source, target)
    (target / "TASK.md").write_text(TASK, encoding="utf-8")
    plan = {
        "schema": "treasury-orchestrator/v1", "worker_kind": "EXTERNALLY_DISPATCHED",
        "max_parallel": 1, "max_wall_seconds": 900, "max_output_bytes": 1048576,
        "tasks": [
            {"id": "generate", "kind": "worker", "depends_on": [], "idempotent": False,
             "max_attempts": 1, "timeout_seconds": 480, "response": "result.json",
             "parameters": {"instruction_file": "TASK.md", "required_artifacts":
                            ["artifacts/spec.md", "artifacts/plan.md", "artifacts/tasks.md"]}},
            {"id": "review", "kind": "worker", "depends_on": ["generate"], "idempotent": False,
             "max_attempts": 1, "timeout_seconds": 300, "response": "result.json",
             "parameters": {"instruction": REVIEW, "required_artifacts": ["review.json"]}},
            {"id": "requirements_approval", "kind": "human", "depends_on": ["review"]},
        ],
    }
    (output / "plan.json").write_text(json.dumps(plan, indent=2) + "\n")
    record = {
        "schema": "sdd-agent-bundle/v1", "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "PREPARED_NOT_EXECUTED", "framework": "Spec Kit", "scaffold_version": "1.2.2",
        "scaffold_source": "practice/sdd/evidence/revision_d4_fresh_scaffold",
        "scaffold_cli_receipt": "practice/sdd/evidence/revision_d4_framework_commands/01_init/RECEIPT.json",
        "source_scaffold_files": original, "pre_edit_input_files": inventory(target),
        "plan_sha256": sha(output / "plan.json"), "preparation_script_sha256": sha(Path(__file__)),
        "answer_specimens_copied": False, "preparation_script_invoked_cli": False,
        "scaffold_cli_initialization_observed": True,
        "model_execution": "NOT_YET_DISPATCHED", "native_skill_discovery": "NOT_OBSERVED",
        "context_isolation": "TASK_INSTRUCTION_ONLY_SHARED_FILESYSTEM",
        "human_review": "PENDING", "model": None,
    }
    (output / "PREPARATION.json").write_text(json.dumps(record, indent=2) + "\n")
    return {"status": record["status"], "output": str(output),
            "input_file_count": len(record["pre_edit_input_files"])}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    print(json.dumps(prepare(args.output), indent=2))


if __name__ == "__main__":
    main()
